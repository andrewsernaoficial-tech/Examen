-- ── PROPIETARIOS ──────────────────────────────────────────────
create table propietarios (
                              id                 number(19,0)  generated by default as identity,
                              dni                varchar2(8  char) not null,
                              nombres            varchar2(100 char) not null,
                              apellidos          varchar2(100 char) not null,
                              telefono           varchar2(15  char),
                              email              varchar2(150 char) not null,
                              direccion          varchar2(250 char),
                              estado             boolean            not null,
                              fecha_creacion     timestamp(6)       not null,
                              fecha_modificacion timestamp(6),
                              constraint pk_propietarios primary key (id),
                              constraint uk_propietarios_dni unique (dni)
);

create unique index ux_propietarios_email on propietarios (upper(email));

-- ── PRESTACIONES ──────────────────────────────────────────────
-- especie_aplicable: TODAS | CANINO | FELINO | AVIAR | EXOTICO
create table prestaciones (
                              id                 number(19,0)  generated by default as identity,
                              codigo             varchar2(20  char) not null,
                              nombre             varchar2(150 char) not null,
                              descripcion        varchar2(300 char),
                              precio             number(10,2)       not null,
                              especie_aplicable  varchar2(20  char) not null,
                              estado             varchar2(20  char) not null,
                              fecha_creacion     timestamp(6)       not null,
                              fecha_modificacion timestamp(6),
                              constraint pk_prestaciones primary key (id),
                              constraint uk_prestaciones_codigo unique (codigo),
                              constraint ck_prestaciones_estado
                                  check (estado in ('ACTIVA', 'INACTIVA')),
                              constraint ck_prestaciones_especie
                                  check (especie_aplicable in ('TODAS','CANINO','FELINO','AVIAR','EXOTICO')),
                              constraint ck_prestaciones_precio check (precio > 0)
);

-- ── MASCOTAS ──────────────────────────────────────────────────
-- Restricción BD: nombre único por propietario
create table mascotas (
                          id                 number(19,0)  generated by default as identity,
                          nombre             varchar2(80  char) not null,
                          especie            varchar2(20  char) not null,
                          raza               varchar2(80  char),
                          fecha_nacimiento   date,
                          peso_kg            number(5,2),
                          propietario_id     number(19,0)       not null,
                          estado             boolean            not null,
                          fecha_creacion     timestamp(6)       not null,
                          fecha_modificacion timestamp(6),
                          constraint pk_mascotas primary key (id),
                          constraint fk_mascotas_propietario
                              foreign key (propietario_id) references propietarios (id),
                          constraint ck_mascotas_especie
                              check (especie in ('CANINO','FELINO','AVIAR','EXOTICO')),
                          constraint ck_mascotas_peso check (peso_kg > 0),
    -- RN-02: nombre único por propietario
                          constraint uk_mascotas_nombre_propietario
                              unique (nombre, propietario_id)
);

create index ix_mascotas_propietario on mascotas (propietario_id);

-- ── ATENCIONES (cabecera) ──────────────────────────────────────
create table atenciones (
                            id                 number(19,0)  generated by default as identity,
                            numero             varchar2(10  char) not null,
                            fecha_hora         timestamp(6)       not null,
                            peso_mascota_kg    number(5,2)        not null,
                            observaciones      varchar2(500 char),
                            subtotal           number(12,2)       not null,
                            descuento          number(12,2)       not null,
                            total              number(12,2)       not null,
                            estado             varchar2(20  char) not null,
                            motivo_anulacion   varchar2(200 char),
                            mascota_id         number(19,0)       not null,
                            constraint pk_atenciones primary key (id),
                            constraint uk_atenciones_numero unique (numero),
                            constraint fk_atenciones_mascota
                                foreign key (mascota_id) references mascotas (id),
                            constraint ck_atenciones_estado
                                check (estado in ('REGISTRADA','ANULADA')),
                            constraint ck_atenciones_peso    check (peso_mascota_kg > 0),
                            constraint ck_atenciones_subtotal check (subtotal >= 0),
                            constraint ck_atenciones_descuento check (descuento >= 0),
                            constraint ck_atenciones_total    check (total >= 0)
);

create index ix_atenciones_mascota   on atenciones (mascota_id);
create index ix_atenciones_fecha     on atenciones (fecha_hora);
create index ix_atenciones_estado    on atenciones (estado);

-- ── DETALLE ATENCIONES ────────────────────────────────────────
create table detalle_atenciones (
                                    id             number(19,0)  generated by default as identity,
                                    atencion_id    number(19,0)  not null,
                                    prestacion_id  number(19,0)  not null,
                                    cantidad       number(2,0)   not null,
                                    precio_unitario number(10,2) not null,
                                    subtotal_linea number(12,2)  not null,
                                    constraint pk_detalle_atenciones primary key (id),
                                    constraint fk_det_aten_atencion
                                        foreign key (atencion_id) references atenciones (id),
                                    constraint fk_det_aten_prestacion
                                        foreign key (prestacion_id) references prestaciones (id),
    -- RN-03: sin prestaciones repetidas en la misma atención
                                    constraint uk_det_aten_prestacion unique (atencion_id, prestacion_id),
                                    constraint ck_det_aten_cantidad check (cantidad between 1 and 3),
                                    constraint ck_det_aten_precio   check (precio_unitario > 0)
);

create index ix_detalle_atenciones_atencion   on detalle_atenciones (atencion_id);
create index ix_detalle_atenciones_prestacion on detalle_atenciones (prestacion_id);